def folder(spec, glyph, opened=False):
    defs = gradient("back", spec["back"], vertical=True) + gradient("front", spec["front"], vertical=True)
    body = (
        f'  <path d="{FOLDER_BACK}" fill="url(#back)"/>\n'
        f"  {FOLDER_FRONT_OPEN if opened else FOLDER_FRONT}\n"
        f"  {glyph}\n"
    )
