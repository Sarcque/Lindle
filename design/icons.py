def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def logo_svg(stops):
    """The standalone logo in design/logo, same art as the brand tile."""
    return tile(stops, GLYPHS["brand"])


def write_icons(tokens):
    icons = tokens["icons"]
    if THEME_DIR.exists():
        shutil.rmtree(THEME_DIR)
    # Only generated files live here, so start clean to drop renamed icons.
    for stale in HICOLOR_APPS.glob("*lindle*.svg"):
        stale.unlink()

    write(THEME_DIR / "index.theme", INDEX_THEME)

    for key, names in TILE_NAMES.items():
        art = tile(icons["tiles"][key], GLYPHS[key])
        for name in names:
            write(THEME_DIR / "scalable" / "apps" / f"{name}.svg", art)

    for name, glyph in FOLDER_GLYPHS.items():
        write(THEME_DIR / "scalable" / "places" / f"{name}.svg", folder(icons["folder"], glyph))
    write(THEME_DIR / "scalable" / "places" / "folder-open.svg", folder(icons["folder"], "", opened=True))
    write(THEME_DIR / "scalable" / "mimetypes" / "inode-directory.svg", folder(icons["folder"], ""))

    # The logo must resolve in every icon theme (login screen, About, other themes).
    brand = tile(icons["tiles"]["brand"], GLYPHS["brand"])
    for name in TILE_NAMES["brand"]:
        write(HICOLOR_APPS / f"{name}.svg", brand)
    write(LOGO_DIR / "lindle-logo.svg", brand)

    count = sum(1 for _ in THEME_DIR.rglob("*.svg"))
    print(f"wrote {THEME_DIR.relative_to(ROOT)} ({count} icons)")


def check_icon_contrast(tokens, contrast):
    """White glyphs must stay readable on both ends of every tile gradient."""
    failures = []
    groups = dict(tokens["icons"]["tiles"])
    groups["folder front"] = tokens["icons"]["folder"]["front"]
    for name, stops in groups.items():
        for stop in stops:
            ratio = contrast(stop, "#FFFFFF")
            if ratio < 3.0:
                failures.append(f"icon {name}: white on {stop} is {ratio:.2f}:1, needs 3.0:1")
    return failures
