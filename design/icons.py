def gradient(gid, stops, vertical=False):
    x2, y2 = ("0", "1") if vertical else ("1", "1")
    return (
        f'  <linearGradient id="{gid}" x1="0" y1="0" x2="{x2}" y2="{y2}">'
        f'<stop offset="0" stop-color="{stops[0]}"/><stop offset="1" stop-color="{stops[1]}"/></linearGradient>\n'
    )


def svg(defs, body):
    return HEADER + SVG_OPEN + "  <defs>\n" + defs + "  </defs>\n" + body + "</svg>\n"


def tile(stops, glyph):
    defs = gradient("g", stops) + (
        '  <linearGradient id="h" x1="0" y1="0" x2="0" y2="1">'
        '<stop offset="0" stop-color="#fff" stop-opacity="0.22"/>'
        '<stop offset="0.55" stop-color="#fff" stop-opacity="0"/></linearGradient>\n'
    )
    body = (
        '  <rect width="128" height="128" rx="30" fill="url(#g)"/>\n'
        '  <rect width="128" height="128" rx="30" fill="url(#h)"/>\n'
        f"  {glyph}\n"
    )
    return svg(defs, body)


