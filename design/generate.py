#!/usr/bin/env python3
"""Generate Lindle's theme files from design/tokens.json.

    python3 design/generate.py            # write color schemes and icons (and wallpapers if Pillow is installed)
    python3 design/generate.py --check    # contrast checks only, exits non-zero on failure

Outputs go into system_files/, which the image build copies over the OS.
"""

import argparse
import json
import sys
from pathlib import Path

import icons

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens.json"
SCHEMES_DIR = ROOT / "system_files" / "usr" / "share" / "color-schemes"
WALLPAPER_DIR = ROOT / "system_files" / "usr" / "share" / "wallpapers" / "Lindle"
LNF_DIR = ROOT / "system_files" / "usr" / "share" / "plasma" / "look-and-feel"
LNF_PACKAGES = {"light": "org.lindle.desktop", "dark": "org.lindle.desktop.dark"}

# WCAG 2.x minimums: 4.5 for body text, 3.0 for large text and UI parts.
CONTRAST_PAIRS = [
    ("text", "window", 4.5),
    ("text", "view", 4.5),
    ("text", "header", 4.5),
    ("text", "button", 4.5),
    ("textMuted", "window", 4.5),
    ("textMuted", "view", 4.5),
    ("tooltipText", "tooltip", 4.5),
    ("accentText", "accent", 4.5),
    ("link", "view", 4.5),
    ("negative", "view", 4.5),
    ("positive", "view", 3.0),
    ("neutral", "view", 3.0),
    ("accent", "view", 3.0),
]


def rgb(hex_color):
    h = hex_color.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def kde(hex_color):
    return ",".join(str(c) for c in rgb(hex_color))


def luminance(hex_color):
    def channel(c):
        c = c / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = (channel(c) for c in rgb(hex_color))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def check_contrast(tokens):
    failures = []
    for mode, palette in tokens["color"].items():
        for fg, bg, minimum in CONTRAST_PAIRS:
            ratio = contrast(palette[fg], palette[bg])
            if ratio < minimum:
                failures.append(f"{mode}: {fg} on {bg} is {ratio:.2f}:1, needs {minimum}:1")
    return failures


def color_group(p, background, background_alt, foreground=None):
    fg = foreground or p["text"]
    return {
        "BackgroundNormal": kde(background),
        "BackgroundAlternate": kde(background_alt),
        "DecorationFocus": kde(p["accent"]),
        "DecorationHover": kde(p["accent"]),
        "ForegroundNormal": kde(fg),
        "ForegroundInactive": kde(p["textMuted"]),
        "ForegroundActive": kde(p["accent"]),
        "ForegroundLink": kde(p["link"]),
        "ForegroundVisited": kde(p["visited"]),
        "ForegroundNegative": kde(p["negative"]),
        "ForegroundNeutral": kde(p["neutral"]),
        "ForegroundPositive": kde(p["positive"]),
    }


def color_scheme(name, p):
    selection = color_group(p, p["accent"], p["accent"], p["accentText"])
    selection["ForegroundInactive"] = kde(p["accentText"])
    selection["ForegroundActive"] = kde(p["accentText"])
    selection["ForegroundLink"] = kde(p["accentText"])
    selection["ForegroundVisited"] = kde(p["accentText"])

    tooltip = color_group(p, p["tooltip"], p["tooltip"], p["tooltipText"])

    sections = {
        "ColorEffects:Disabled": {
            "Color": kde(p["window"]), "ColorAmount": "0", "ColorEffect": "0",
            "ContrastAmount": "0.65", "ContrastEffect": "1",
            "IntensityAmount": "0.1", "IntensityEffect": "2",
        },
        "ColorEffects:Inactive": {
            "ChangeSelectionColor": "true", "Color": kde(p["window"]),
            "ColorAmount": "0.025", "ColorEffect": "2", "ContrastAmount": "0.1",
            "ContrastEffect": "2", "Enable": "false",
            "IntensityAmount": "0", "IntensityEffect": "0",
        },
        "Colors:Button": color_group(p, p["button"], p["windowAlt"]),
        "Colors:Complementary": color_group(p, p["window"], p["windowAlt"]),
        "Colors:Header": color_group(p, p["header"], p["windowAlt"]),
        "Colors:Header][Inactive": color_group(p, p["window"], p["windowAlt"]),
        "Colors:Selection": selection,
        "Colors:Tooltip": tooltip,
        "Colors:View": color_group(p, p["view"], p["viewAlt"]),
        "Colors:Window": color_group(p, p["window"], p["windowAlt"]),
        "General": {"ColorScheme": name, "Name": name.replace("Lindle", "Lindle "), "shadeSortColumn": "true"},
        "KDE": {"contrast": "4"},
        "WM": {
            "activeBackground": kde(p["header"]),
            "activeBlend": kde(p["text"]),
            "activeForeground": kde(p["text"]),
            "inactiveBackground": kde(p["window"]),
            "inactiveBlend": kde(p["textMuted"]),
            "inactiveForeground": kde(p["textMuted"]),
        },
    }

    lines = ["# Generated by design/generate.py from design/tokens.json. Do not edit by hand.", ""]
    for section, values in sections.items():
        lines.append(f"[{section}]")
        lines.extend(f"{k}={v}" for k, v in values.items())
        lines.append("")
    return "\n".join(lines)


def write_schemes(tokens):
    SCHEMES_DIR.mkdir(parents=True, exist_ok=True)
    for mode, name in (("light", "LindleLight"), ("dark", "LindleDark")):
        path = SCHEMES_DIR / f"{name}.colors"
        path.write_text(color_scheme(name, tokens["color"][mode]))
        print(f"wrote {path.relative_to(ROOT)}")


def render_wallpaper(spec, size):
    import random

    from PIL import Image, ImageDraw, ImageFilter

    w, h = size
    # Draw at quarter size, blur, then scale up: soft gradients without heavy work at 4K.
    sw, sh = w // 4, h // 4
    img = Image.new("RGB", (sw, sh), rgb(spec["base"]))
    layer = Image.new("RGB", (sw, sh), rgb(spec["base"]))
    draw = ImageDraw.Draw(layer)
    # Fixed positions keep the output stable between runs.
    shapes = [(0.12, 0.78, 0.55), (0.78, 0.22, 0.5), (0.6, 0.95, 0.4)]
    for (cx, cy, r), color in zip(shapes, spec["blobs"]):
        rad = r * sh
        draw.ellipse((cx * sw - rad, cy * sh - rad, cx * sw + rad, cy * sh + rad), fill=rgb(color))
    layer = layer.filter(ImageFilter.GaussianBlur(sh * 0.18))
    img = Image.blend(img, layer, 0.85).resize((w, h), Image.BICUBIC)
    # A little seeded grain hides 8-bit banding in the dark gradients.
    rng = random.Random(7)
    noise = Image.frombytes("L", (w, h), bytes(rng.randrange(118, 138) for _ in range(w * h)))
    return Image.blend(img, Image.merge("RGB", (noise, noise, noise)), 0.03)


def write_wallpapers(tokens):
    try:
        import PIL  # noqa: F401
    except ImportError:
        print("Pillow not installed, skipping wallpapers")
        return
    for mode, folder in (("light", "images"), ("dark", "images_dark")):
        out = WALLPAPER_DIR / "contents" / folder
        out.mkdir(parents=True, exist_ok=True)
        render_wallpaper(tokens["wallpaper"][mode], (3840, 2160)).save(out / "3840x2160.png", optimize=True)
        print(f"wrote {(out / '3840x2160.png').relative_to(ROOT)}")
    metadata = {
        "KPlugin": {
            "Authors": [{"Name": "Lindle Contributors"}],
            "Id": "Lindle",
            "License": "CC-BY-SA-4.0",
            "Name": "Lindle",
        }
    }
    (WALLPAPER_DIR / "metadata.json").write_text(json.dumps(metadata, indent=4) + "\n")


def render_preview(tokens, mode, wallpaper):
    """A simplified desktop (window plus floating panel) for the theme picker."""
    from PIL import Image, ImageDraw

    p = tokens["color"][mode]
    r = tokens["radius"]
    w, h = 1920, 1080
    img = wallpaper.resize((w, h), Image.LANCZOS).convert("RGBA")

    shadow = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ImageDraw.Draw(shadow).rounded_rectangle((470, 170, 1470, 830), r["large"] * 2, fill=(0, 0, 0, 60))
    from PIL import ImageFilter
    img = Image.alpha_composite(img, shadow.filter(ImageFilter.GaussianBlur(24)))

    d = ImageDraw.Draw(img)
    # Window: header bar, sidebar, content with a few rows and an accent button.
    d.rounded_rectangle((460, 150, 1460, 810), r["large"] * 2, fill=rgb(p["window"]))
    d.rounded_rectangle((460, 150, 1460, 230), r["large"] * 2, fill=rgb(p["header"]))
    d.rectangle((460, 200, 1460, 230), fill=rgb(p["header"]))
    for i, x in enumerate((1400, 1360, 1320)):
        d.ellipse((x, 180, x + 20, 200), fill=rgb(p["textMuted"]))
    d.rounded_rectangle((480, 250, 720, 790), r["medium"] * 2, fill=rgb(p["windowAlt"]))
    d.rounded_rectangle((495, 268, 705, 312), r["small"] * 2, fill=rgb(p["accent"]))
    for i in range(5):
        y = 330 + i * 52
        d.rounded_rectangle((510, y, 520 + 120 + (i * 23) % 50, y + 16), 8, fill=rgb(p["textMuted"]))
    d.rounded_rectangle((740, 250, 1440, 790), r["medium"] * 2, fill=rgb(p["view"]))
    d.rounded_rectangle((780, 290, 1100, 320), 10, fill=rgb(p["text"]))
    for i in range(6):
        y = 360 + i * 48
        d.rounded_rectangle((780, y, 1400 - (i * 61) % 180, y + 18), 9, fill=rgb(p["viewAlt"] if i % 2 else p["windowAlt"]))
    d.rounded_rectangle((1240, 720, 1410, 768), r["small"] * 2, fill=rgb(p["accent"]))

    # Floating panel with launcher dots, the first one active.
    d.rounded_rectangle((560, 960, 1360, 1040), r["large"] * 2, fill=rgb(p["window"]))
    for i in range(9):
        x = 600 + i * 76
        fill = p["accent"] if i == 0 else (p["windowAlt"] if mode == "light" else p["button"])
        d.rounded_rectangle((x, 976, x + 48, 1024), r["small"] * 2, fill=rgb(fill))
    return img.convert("RGB")


def write_previews(tokens):
    try:
        from PIL import Image
    except ImportError:
        print("Pillow not installed, skipping theme previews")
        return
    for mode, folder in (("light", "images"), ("dark", "images_dark")):
        wallpaper = Image.open(WALLPAPER_DIR / "contents" / folder / "3840x2160.png")
        full = render_preview(tokens, mode, wallpaper)
        out = LNF_DIR / LNF_PACKAGES[mode] / "contents" / "previews"
        out.mkdir(parents=True, exist_ok=True)
        full.save(out / "fullscreenpreview.jpg", quality=88, optimize=True)
        full.resize((640, 360), Image.LANCZOS).save(out / "preview.png", optimize=True)
        print(f"wrote {out.relative_to(ROOT)}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="only run contrast checks")
    args = parser.parse_args()

    tokens = json.loads(TOKENS.read_text())
    failures = check_contrast(tokens) + icons.check_icon_contrast(tokens, contrast)
    for f in failures:
        print(f"contrast: {f}", file=sys.stderr)
    if failures:
        sys.exit(1)
    print("contrast checks passed")

    if args.check:
        return
    write_schemes(tokens)
    icons.write_icons(tokens)
    write_wallpapers(tokens)
    write_previews(tokens)


if __name__ == "__main__":
    main()
