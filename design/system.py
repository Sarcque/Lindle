def _logo_tile(size, stops, accent_l=True):
    """The Lindle mark (gradient tile with the L), drawn supersampled."""
    from PIL import Image, ImageDraw

    scale = 4
    s = size * scale
    top, bottom = rgb(stops[0]), rgb(stops[1])
    grad = Image.new("RGB", (s, s))
    px = grad.load()
    for y in range(s):
        for x in range(s):
            t = (x + y) / (2 * (s - 1))
            px[x, y] = tuple(round(top[i] + (bottom[i] - top[i]) * t) for i in range(3))
    mask = Image.new("L", (s, s), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, s - 1, s - 1), round(s * 30 / 128), fill=255)
    tile = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    tile.paste(grad, (0, 0), mask)

    # The L from the mark (M44 32 v52 a12 12 0 0 0 12 12 h30), stroked 14 wide
    # with round caps by stamping circles along the path.
    d = ImageDraw.Draw(tile)
    k = s / 128
    r = 7 * k
    pts = [(44, 32 + i * 0.25) for i in range(int(52 / 0.25) + 1)]
    pts += [(56 - 12 * math.cos(a), 84 + 12 * math.sin(a))
            for a in (i * math.pi / 2 / 40 for i in range(41))]
    pts += [(56 + i * 0.25, 96) for i in range(int(30 / 0.25) + 1)]
    for x, y in pts:
        d.ellipse((x * k - r, y * k - r, x * k + r, y * k + r), fill="white")
    return tile.resize((size, size), Image.LANCZOS)


def plymouth_script(tokens):
    bg = rgb(tokens["wallpaper"]["dark"]["base"])
    c = [round(v / 255, 3) for v in bg]
    return f"""// Generated by design/generate.py from design/tokens.json. Do not edit by hand.
// Lindle boot splash: the mark on a dark background, with a thin progress bar.

Window.SetBackgroundTopColor({c[0]}, {c[1]}, {c[2]});
Window.SetBackgroundBottomColor({c[0]}, {c[1]}, {c[2]});

logo.image = Image("logo.png");
logo.sprite = Sprite(logo.image);
logo.x = Window.GetX() + Window.GetWidth() / 2 - logo.image.GetWidth() / 2;
logo.y = Window.GetY() + Window.GetHeight() / 2 - logo.image.GetHeight() / 2 - 40;
logo.sprite.SetPosition(logo.x, logo.y, 10);

track.image = Image("track.png");
track.sprite = Sprite(track.image);
track.x = Window.GetX() + Window.GetWidth() / 2 - track.image.GetWidth() / 2;
track.y = logo.y + logo.image.GetHeight() + 64;
track.sprite.SetPosition(track.x, track.y, 10);

bar.image = Image("bar.png");
bar.sprite = Sprite();
bar.sprite.SetPosition(track.x, track.y, 11);

fun refresh_callback() {{
    // A slow pulse, so the screen never looks frozen.
    logo.sprite.SetOpacity(0.88 + 0.12 * Math.Sin(global.pulse));
    global.pulse = global.pulse + 0.08;
}}
global.pulse = 0;
Plymouth.SetRefreshFunction(refresh_callback);

fun boot_progress_callback(time, progress) {{
    width = Math.Int(track.image.GetWidth() * progress);
    if (width < 8) width = 8;
    bar.sprite.SetImage(bar.image.Scale(width, bar.image.GetHeight()));
}}
Plymouth.SetBootProgressFunction(boot_progress_callback);

// Disk encryption password prompt: bullets under the mark.
prompt.sprite = Sprite();
bullets.sprite = Sprite();
fun display_password_callback(prompt_text, bullet_count) {{
    prompt.sprite.SetImage(Image.Text(prompt_text, 0.93, 0.93, 0.95, 1, "Inter 12"));
    prompt.sprite.SetPosition(Window.GetX() + Window.GetWidth() / 2 - prompt.sprite.GetImage().GetWidth() / 2, track.y + 40, 20);
    text = "";
    for (i = 0; i < bullet_count; i++) text += "•";
    bullets.sprite.SetImage(Image.Text(text, 0.93, 0.93, 0.95, 1, "Inter 14"));
    bullets.sprite.SetPosition(Window.GetX() + Window.GetWidth() / 2 - bullets.sprite.GetImage().GetWidth() / 2, track.y + 76, 20);
}}
Plymouth.SetDisplayPasswordFunction(display_password_callback);

fun display_normal_callback() {{
    prompt.sprite.SetOpacity(0);
    bullets.sprite.SetOpacity(0);
}}
Plymouth.SetDisplayNormalFunction(display_normal_callback);

message.sprite = Sprite();
fun display_message_callback(text) {{
    message.sprite.SetImage(Image.Text(text, 0.7, 0.72, 0.8, 1, "Inter 11"));
    message.sprite.SetPosition(Window.GetX() + Window.GetWidth() / 2 - message.sprite.GetImage().GetWidth() / 2, Window.GetHeight() - 60, 20);
}}
Plymouth.SetDisplayMessageFunction(display_message_callback);
Plymouth.SetMessageFunction(display_message_callback);
"""


def write_boot(tokens):
    wp = tokens["wallpaper"]["dark"]
    write(PLYMOUTH_DIR / "lindle.plymouth", (
        "[Plymouth Theme]\nName=Lindle\nDescription=The Lindle mark on a dark background\n"
        "ModuleName=script\n\n[script]\n"
        "ImageDir=/usr/share/plymouth/themes/lindle\n"
        "ScriptFile=/usr/share/plymouth/themes/lindle/lindle.script\n"
    ))
    write(PLYMOUTH_DIR / "lindle.script", plymouth_script(tokens))
    write(GRUB_DIR / "theme.txt", f"""# Generated by design/generate.py from design/tokens.json. Do not edit by hand.
desktop-image: "background.png"
desktop-color: "{wp['base']}"
title-text: ""
terminal-font: "Unifont Regular 16"
+ boot_menu {{
    left = 25%
    top = 52%
    width = 50%
    height = 38%
    item_font = "Unifont Regular 16"
    item_color = "{tokens['color']['dark']['textMuted']}"
    selected_item_font = "Unifont Regular 16"
    selected_item_color = "{tokens['color']['dark']['text']}"
    item_height = 36
    item_padding = 10
    item_spacing = 6
    icon_width = 0
    icon_height = 0
}}
+ progress_bar {{
    id = "__timeout__"
    left = 25%
    top = 92%
    width = 50%
    height = 4
    fg_color = "{tokens['color']['dark']['accent']}"
    bg_color = "{tokens['color']['dark']['windowAlt']}"
    border_color = "{tokens['color']['dark']['windowAlt']}"
}}
""")

    try:
        from PIL import Image, ImageDraw
    except ImportError:
        print("Pillow not installed, skipping boot images")
        return

    stops = tokens["icons"]["tiles"]["brand"]
    PLYMOUTH_DIR.mkdir(parents=True, exist_ok=True)
    _logo_tile(160, stops).save(PLYMOUTH_DIR / "logo.png", optimize=True)

    def pill(width, height, color):
        scale = 4
        img = Image.new("RGBA", (width * scale, height * scale), (0, 0, 0, 0))
        ImageDraw.Draw(img).rounded_rectangle((0, 0, width * scale - 1, height * scale - 1), height * scale // 2, fill=color)
        return img.resize((width, height), Image.LANCZOS)

    dark = tokens["color"]["dark"]
    pill(240, 4, rgb(dark["windowAlt"]) + (255,)).save(PLYMOUTH_DIR / "track.png", optimize=True)
    pill(240, 4, rgb(dark["accent"]) + (255,)).save(PLYMOUTH_DIR / "bar.png", optimize=True)

    # GRUB background: dark base with the mark centered above the menu.
    w, h = 1920, 1080
    bg = Image.new("RGBA", (w, h), rgb(wp["base"]) + (255,))
    mark = _logo_tile(160, stops)
    bg.alpha_composite(mark, (w // 2 - 80, 150))
    GRUB_DIR.mkdir(parents=True, exist_ok=True)
    bg.convert("RGB").save(GRUB_DIR / "background.png", optimize=True)
    print(f"wrote {PLYMOUTH_DIR.relative_to(ROOT)} and {GRUB_DIR.relative_to(ROOT)} images")


# ----------------------------------------------------------------------- All

def write_system(tokens):
    write(QML_DIR / "Theme.qml", qml_theme(tokens))
    write(GREETER_DIR / "kdeglobals", greeter_kdeglobals(tokens))
    write(XDG_DIR / "breezerc", breezerc(tokens))
    write_sounds()
    write_boot(tokens)
