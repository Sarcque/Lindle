RATE = 32000

# Pentatonic notes (Hz), so every sound is consonant with every other.
N = {"C5": 523.25, "D5": 587.33, "E5": 659.25, "G5": 783.99, "A5": 880.0, "C6": 1046.5,
     "G4": 392.0, "A4": 440.0, "E4": 329.63, "C4": 261.63}

SOUNDS = {
    "desktop-login": [("C5", 0.0, 0.5), ("E5", 0.14, 0.5), ("G5", 0.28, 0.9)],
    "desktop-logout": [("G5", 0.0, 0.4), ("E5", 0.14, 0.4), ("C5", 0.28, 0.8)],
    "message": [("G5", 0.0, 0.5)],
    "message-new-instant": [("E5", 0.0, 0.35), ("A5", 0.12, 0.6)],
    "dialog-information": [("A5", 0.0, 0.5)],
    "dialog-warning": [("E5", 0.0, 0.3), ("E5", 0.2, 0.5)],
    "dialog-error": [("A4", 0.0, 0.3), ("E4", 0.16, 0.6)],
    "bell": [("C6", 0.0, 0.7)],
    "complete": [("C5", 0.0, 0.3), ("E5", 0.09, 0.3), ("G5", 0.18, 0.3), ("C6", 0.27, 0.8)],
    "device-added": [("E5", 0.0, 0.3), ("A5", 0.11, 0.6)],
    "device-removed": [("A5", 0.0, 0.3), ("E5", 0.11, 0.6)],
    "battery-low": [("A4", 0.0, 0.3), ("A4", 0.25, 0.3), ("A4", 0.5, 0.5)],
    "window-close": [("G4", 0.0, 0.25)],
    "trash-empty": [("G5", 0.0, 0.2), ("E5", 0.07, 0.2), ("C5", 0.14, 0.4)],
}


def render_sound(notes):
    total = max(start + length for _, start, length in notes) + 0.05
    samples = [0.0] * int(RATE * total)
    for name, start, length in notes:
        f = N[name]
        offset = int(RATE * start)
        for i in range(int(RATE * length)):
            t = i / RATE
            env = min(1.0, t / 0.006) * math.exp(-t * (5.0 / length))
            # A soft bell: fundamental plus a quiet octave and a fifth above.
            v = math.sin(2 * math.pi * f * t) + 0.3 * math.sin(2 * math.pi * 2 * f * t) + 0.1 * math.sin(2 * math.pi * 3 * f * t)
            if offset + i < len(samples):
                samples[offset + i] += 0.28 * env * v
    peak = max(1.0, max(abs(s) for s in samples))
    return [int(32767 * 0.8 * s / peak) for s in samples]


def write_sounds():
    out = SOUNDS_DIR / "stereo"
    out.mkdir(parents=True, exist_ok=True)
    for name, notes in SOUNDS.items():
        data = render_sound(notes)
        with wave.open(str(out / f"{name}.wav"), "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(RATE)
            w.writeframes(struct.pack(f"<{len(data)}h", *data))
    (SOUNDS_DIR / "index.theme").write_text(
        "[Sound Theme]\nName=Lindle\nComment=Soft chimes for Lindle\n"
        "Inherits=ocean,freedesktop\nDirectories=stereo\n\n[stereo]\nOutputProfile=stereo\n"
    )
    print(f"wrote {SOUNDS_DIR.relative_to(ROOT)} ({len(SOUNDS)} sounds)")


